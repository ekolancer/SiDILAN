const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { Date, JSON, Set, Map, Math, Number, String, Array, Object, RegExp, console };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'Code.js'), 'utf8'), context);
const own = value => JSON.parse(JSON.stringify(value));
let writes = [];
let released = 0;
let current = { rowHint: 2, agenda: '354.a', expectedHash: 'original', followupNote: '', letterPosition: '', sender: 'Asal', subject: 'Hal', letterNumber: '001', receivedDate: '2026-10-14', letterDate: '', documentDescription: '' };
const sheet = { getLastRow: () => 2, getSheetId: () => 7 };
context.requireRole_ = () => ({ config: { spreadsheetId: 'copy', sheetName: 'SuratMasuk' } });
context.LockService = { getScriptLock: () => ({ tryLock: () => true, releaseLock: () => { released++; } }) };
context.getValidatedSheet_ = () => sheet;
context.readRecordAtRow_ = () => current;
context.ensureUniqueAgenda_ = () => {};
context.readRegister_ = () => ({ records: [current] });
context.collectPositions_ = () => ['', 'Baru Masuk'];
context.SpreadsheetApp = { flush() {} };
context.Sheets = { Spreadsheets: { batchUpdate: body => { writes.push(own(body)); current = { ...current, followupNote: 'Diproses', expectedHash: 'new' }; } } };
const payload = { rowHint: 2, agenda: '354.a', expectedHash: 'original', changes: { followupNote: 'Diproses' } };
assert.equal(own(context.updateSuratMasuk({ ...payload, expectedHash: 'stale' })).error, 'DATA_CHANGED');
assert.equal(writes.length, 0);
assert.equal(own(context.updateSuratMasuk({ ...payload, agenda: 'other' })).error, 'DATA_CHANGED');
assert.equal(writes.length, 0);
const saved = own(context.updateSuratMasuk(payload));
assert.equal(saved.success, true);
assert.equal(writes.length, 1);
assert.equal(writes[0].requests.length, 1);
assert.equal(writes[0].requests[0].updateCells.range.startColumnIndex, 12);
assert.equal(writes[0].requests[0].updateCells.fields, 'userEnteredValue');
assert.equal(writes[0].requests[0].updateCells.rows[0].values[0].userEnteredValue.stringValue, 'Diproses');
assert.equal(released, 3);
current = { ...current, expectedHash: 'new', documentDescription: 'Uraian lama' };
const regenerate = own(context.updateSuratMasuk({ rowHint: 2, agenda: '354.a', expectedHash: 'new', changes: { subject: 'Hal baru' }, updateDescription: true }));
assert.equal(regenerate.success, true);
assert.equal(writes.length, 2);
assert.deepEqual(writes[1].requests.map(request => request.updateCells.range.startColumnIndex), [5, 6]);
assert.equal(writes[1].requests[1].updateCells.rows[0].values[0].userEnteredValue.stringValue, 'Asal - 001 - Tanggal surat belum tersedia - Hal baru');
current = { ...current, expectedHash: 'new', letterFileReference: '' };
const linkWrite = own(context.updateSuratMasuk({ rowHint: 2, agenda: '354.a', expectedHash: 'new', changes: { letterFileReference: 'https://example.com/file' } }));
assert.equal(linkWrite.success, true);
assert.equal(writes[2].requests[0].updateCells.fields, 'userEnteredValue,textFormatRuns,userEnteredFormat.textFormat.link');
context.requireRole_ = () => { throw new Error('ACCESS_DENIED'); };
assert.equal(own(context.updateSuratMasuk(payload)).error, 'ACCESS_DENIED');
assert.equal(writes.length, 3);
console.log('edit conflict and partial write checks passed');
